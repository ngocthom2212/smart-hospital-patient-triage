package Model;

import java.util.Date;

/**
 *
 * @author buidi
 */
public class Patient {
    private String id;
    private String name;
    private Boolean gender;
    private Date dob;

    public Patient(String id, String name, Boolean gender, Date dob) {
        this.id = id;
        this.name = name;
        this.gender = gender;
        this.dob = dob;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Boolean getGender() {
        return gender;
    }

    public void setGender(Boolean gender) {
        this.gender = gender;
    }

    public Date getDob() {
        return dob;
    }

    public void setDob(Date dob) {
        this.dob = dob;
    }
    
    public int getAge() {
        return -1; 
    }
}
